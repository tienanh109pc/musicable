class I18nManager {
    constructor() {
        this.currentLang = localStorage.getItem('musicable_lang') || 'en';
    }

    setLanguage(lang) {
        if (!I18N_TRANSLATIONS[lang]) return;
        this.currentLang = lang;
        localStorage.setItem('musicable_lang', lang);
        this.updateDOM();
        document.documentElement.lang = lang;
    }

    getLanguage() {
        return this.currentLang;
    }

    t(key, replacements = {}) {
        const langData = I18N_TRANSLATIONS[this.currentLang] || I18N_TRANSLATIONS.en;
        let text = langData[key] || I18N_TRANSLATIONS.en[key] || key;
        for (const [k, v] of Object.entries(replacements)) {
            text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
        }
        return text;
    }

    updateDOM() {
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            const translation = this.t(key);
            if (el.tagName === 'INPUT' && el.getAttribute('placeholder')) {
                el.placeholder = translation;
            } else {
                el.textContent = translation;
            }
        });

        document.querySelectorAll('[data-i18n-title]').forEach(el => {
            const key = el.getAttribute('data-i18n-title');
            el.title = this.t(key);
        });

        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            el.placeholder = this.t(key);
        });
    }
}

window.I18n = new I18nManager();
